
import streamlit as st
import pandas as pd
import joblib
from num2words import num2words

# Load the trained model
model = joblib.load("used_car_price_model.pkl")

st.title("🚗 Used Car Price Prediction")
st.write("Predict the estimated selling price of a used car.")

st.subheader("Enter Car Details")


year = st.selectbox(
    "Manufacturing Year",
    options=list(range(2026, 1990 - 1, -1)),
    index=8
)

km_driven = st.number_input(
    "Kilometers Driven",
    min_value=0,
    value=50000,
    step=1000
)

fuel = st.selectbox(
    "Fuel Type",
    ["Diesel", "Petrol", "CNG", "LPG"]
)

seller_type = st.selectbox(
    "Seller Type",
    ["Individual", "Dealer", "Trustmark Dealer"]
)

transmission = st.selectbox(
    "Transmission",
    ["Manual", "Automatic"]
)

owner = st.selectbox(
    "Owner",
    [
        "First Owner",
        "Second Owner",
        "Third Owner",
        "Fourth & Above Owner",
        "Test Drive Car"
    ]
)




brand = st.selectbox(
    "Car Brand",
    [
        "Ambassador", "Audi", "BMW", "Chevrolet",
        "Daewoo", "Datsun", "Fiat", "Force", "Ford",
        "Honda", "Hyundai", "Isuzu", "Jaguar", "Jeep",
        "Kia", "Land", "MG", "Mahindra", "Maruti",
        "Mercedes-Benz", "Mitsubishi", "Nissan",
        "OpelCorsa", "Renault", "Skoda", "Tata",
        "Toyota", "Volkswagen", "Volvo"
    ]
)


car_age = 2026 - year



if st.button("Predict Car Price"):
    input_data = pd.DataFrame([{
        "year": year,
        "km_driven": km_driven,
        "fuel": fuel,
        "seller_type": seller_type,
        "transmission": transmission,
        "owner": owner,
        "car_age": 2026 - year,
        "brand": brand.strip().title()
    }])

    predicted_price = model.predict(input_data)[0]

    st.success("Prediction completed!")

    st.subheader("🚗 Your Car Details")

    col1, col2 = st.columns(2)

    with col1:
        st.write("**Brand:**", brand)
        st.write("**Manufacturing Year:**", year)
        st.write("**Fuel Type:**", fuel)
        st.write("**Kilometers Driven:**", f"{km_driven:,} km")

    with col2:
        st.write("**Seller Type:**", seller_type)
        st.write("**Transmission:**", transmission)
        st.write("**Owner:**", owner)
        st.write("**Car Age:**", f"{2026 - year} years")

    st.divider()

    st.subheader("💰 Estimated Selling Price")
    st.markdown(f"## ₹{predicted_price:,.0f}")

    price_in_words = num2words(
        int(round(predicted_price)),
        lang="en_IN"
    )

    st.write(f"**In Words:** {price_in_words.title()} Rupees Only")

    st.caption(
        "This is an estimated price generated by your machine-learning model. "
        "The actual selling price may vary."
        "This Project Is Created By Tripti Kedia."
    )
